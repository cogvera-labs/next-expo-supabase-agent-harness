// The content loader for Starlight's `docs` collection. It reads the corpus IN PLACE: the
// template docs and the repository documents, beside the site's own pages.
//
// Why not glob(), or Starlight's docsLoader(), which is glob() with a fixed base:
//   1. glob() validates the data with parseData BEFORE it renders, and the corpus has no
//      frontmatter, so the `title` Starlight requires must exist before the Markdown is
//      parsed. Here the render runs first and the title comes out of it (markdown-plugins.mjs).
//   2. starlight-links-validator keys each page by `frontmatter.slug`, else by the file's
//      path relative to src/content/docs. A file outside that folder matches no route, so
//      every link INTO the page would be reported invalid. The render carries a `slug`.
//   3. Starlight reads git dates only for src/content/docs, so `lastUpdated` is set here.
// Only documented LoaderContext APIs are used: renderMarkdown, parseData, store,
// generateDigest, logger and watcher.
import { existsSync } from 'node:fs'
import { readFile } from 'node:fs/promises'
import { dirname, join, posix, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { DEFAULT_BRANCH, GITHUB_REPO, REPO_ROOT, loadCorpus, pageSourcePaths, repoRelative, sitePages } from './corpus.mjs'
import { PAGE_TITLE_MAX, TITLE_MAX, documentTitle } from './head.mjs'
import { lastCommitDates } from './page-dates.mjs'
import { fillSiteValues } from './site-values.mjs'

/**
 * Each page's "last updated" date, by repo-relative path. A shallow clone has no history to
 * read, so there every page carries the newest commit's date, and the build log says so.
 */
function lastUpdatedDates(logger) {
  const { dates, shallow, failure } = lastCommitDates(pageSourcePaths(), REPO_ROOT)
  if (failure) logger.warn(`git log failed (${failure}); pages ship without "last updated"`)
  else if (shallow) logger.warn('shallow clone: "last updated" shows the checkout commit for every page (pages.yml fetches full history)')
  return dates
}

/**
 * The edit link: the file itself, or for a page generated from a register
 * (`<!-- GENERATED by <tool> from <register>`), the register. Its path is read in the tree
 * the page installs from, or from the repository root for a repository document.
 */
function editUrlFor(page, source) {
  const generated = /<!--\s*GENERATED by \S+ from (\S+)/.exec(source.slice(0, 600))
  if (!generated) return `${GITHUB_REPO}/edit/${DEFAULT_BRANCH}/${page.repoPath}`
  const tree = page.installPath ? page.repoPath.slice(0, page.repoPath.indexOf('/docs/')) : ''
  const register = posix.join(tree, generated[1])
  if (!existsSync(join(REPO_ROOT, register))) {
    throw new Error(`${page.repoPath}: its GENERATED banner names ${register}, which does not exist`)
  }
  return `${GITHUB_REPO}/edit/${DEFAULT_BRANCH}/${register}`
}

const hasFrontmatter = (source) => (source.charCodeAt(0) === 0xfeff ? source.slice(1) : source).startsWith('---')

/** A short <title> and og:title from page-meta.mjs, where the H1 is long. The page still shows its H1. */
const titleHead = (title) => [
  { tag: 'title', content: documentTitle(title) },
  { tag: 'meta', attrs: { property: 'og:title', content: title } },
]

/** Say so in the build log when a page's own heading makes its <title> longer than a search result shows. */
function noteTitle(page, heading, logger) {
  if (page.meta.title || heading.length <= PAGE_TITLE_MAX) return
  logger.warn(
    `${page.repoPath}: its heading is ${String(heading.length)} characters, so its <title> is over ${String(TITLE_MAX)}; give it a title of at most ${String(PAGE_TITLE_MAX)} in page-meta.mjs`,
  )
}

/** Say so in the build log when a page's description is the first paragraph cut short, or missing. */
function noteDescription(page, description, logger) {
  if (page.meta.description) return
  if (description === undefined) {
    logger.warn(`${page.repoPath}: no opening paragraph to describe the page, so it repeats the site's description; add one, or a description in page-meta.mjs`)
  } else if (description.endsWith('…')) {
    logger.warn(`${page.repoPath}: its first paragraph is over 160 characters, so its description is cut mid-sentence; shorten it, or describe the page in page-meta.mjs`)
  }
}

/** One of the site's own pages: its frontmatter is its data, after its build-time values are filled in. */
async function renderSitePage(page, source, renderMarkdown) {
  const filled = await fillSiteValues(source, page.repoPath)
  const rendered = await renderMarkdown(filled, { fileURL: page.fileURL })
  return { body: filled, input: filled, rendered, data: rendered.metadata.frontmatter ?? {} }
}

/**
 * A page read in place gets a synthetic frontmatter block with its `slug` and any description
 * from page-meta.mjs; its title, and otherwise its description, come out of the render.
 */
async function renderReadInPlace(page, source, renderMarkdown, logger) {
  // Read in place, a page has no frontmatter by contract; fail closed if that ever changes.
  if (hasFrontmatter(source)) throw new Error(`${page.repoPath}: unexpected frontmatter (the site takes the title from the first "# " heading)`)
  const fields = { slug: page.route, ...(page.meta.description ? { description: page.meta.description } : {}) }
  const input = `---\n${Object.entries(fields).map(([key, value]) => `${key}: ${JSON.stringify(value)}`).join('\n')}\n---\n${source}`
  const rendered = await renderMarkdown(input, { fileURL: page.fileURL })
  const { slug: _slug, ...frontmatter } = rendered.metadata.frontmatter ?? {}
  if (typeof frontmatter.title !== 'string' || frontmatter.title === '') {
    throw new Error(`${page.repoPath}: no top-level "# " heading to take the page title from`)
  }
  noteTitle(page, frontmatter.title, logger)
  noteDescription(page, frontmatter.description, logger)
  const head = page.meta.title ? { head: titleHead(page.meta.title) } : {}
  return { body: source, input, rendered, data: { ...frontmatter, ...head, editUrl: editUrlFor(page, source) } }
}

/** Render one page and assemble its data before validation. */
async function renderPage(page, renderMarkdown, dates, logger) {
  const source = await readFile(page.absPath, 'utf8')
  const out = page.local ? await renderSitePage(page, source, renderMarkdown) : await renderReadInPlace(page, source, renderMarkdown, logger)
  const lastUpdated = dates.get(page.repoPath)
  if (lastUpdated && out.data.lastUpdated === undefined) out.data = { ...out.data, lastUpdated }
  return out
}

export function harnessDocsLoader() {
  return {
    name: 'harness-docs-loader',
    async load({ config, store, parseData, renderMarkdown, generateDigest, logger, watcher }) {
      const root = fileURLToPath(config.root)
      const allPages = () => [...sitePages(), ...loadCorpus().pages]

      async function sync() {
        const all = allPages()
        const dates = lastUpdatedDates(logger)
        const seen = new Set()
        for (const page of all) {
          if (seen.has(page.route)) throw new Error(`two pages claim the route "/${page.route}"`)
          seen.add(page.route)
          const { body, input, rendered, data } = await renderPage(page, renderMarkdown, dates, logger)
          store.set({
            id: page.route,
            data: await parseData({ id: page.route, data, filePath: page.absPath }),
            body,
            filePath: relative(root, page.absPath).split(sep).join('/'),
            digest: generateDigest(input),
            rendered,
          })
        }
        for (const id of store.keys()) if (!seen.has(id)) store.delete(id)
        const readInPlace = loadCorpus().pages.length
        logger.info(`loaded ${String(all.length)} page(s) (${String(readInPlace)} read in place from the repository)`)
      }

      await sync()

      // `astro dev` only: re-render when a page's file changes. An added or deleted file
      // changes the routes and the sidebar, which are computed when astro.config.mjs loads,
      // so those need a restart of the dev server.
      if (!watcher) return
      const watched = new Set(allPages().map((p) => p.absPath))
      for (const dir of new Set([...watched].map((p) => dirname(p)))) watcher.add(dir)
      watcher.on('change', async (changed) => {
        if (!watched.has(changed)) return
        logger.info(`re-rendering ${repoRelative(changed)}`)
        await sync()
      })
    },
  }
}
