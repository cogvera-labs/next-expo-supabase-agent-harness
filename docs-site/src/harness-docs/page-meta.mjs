/** The entry for a page, or an empty one. */
export const pageMetaFor = (repoPath) => (Object.hasOwn(PAGE_META, repoPath) ? PAGE_META[repoPath] : {})

/** Why one field of an entry breaks the rules above, or undefined. */
function fieldProblem(field, value) {
  if (!Object.hasOwn(LIMITS, field)) return `"${field}" is not a field (description, title, label)`
  if (typeof value !== 'string' || value.trim() !== value || value === '') return `${field} must be a trimmed, non-empty string`
  if (value.length > LIMITS[field]) return `${field} is ${String(value.length)} characters; the limit is ${String(LIMITS[field])}`
  if (field === 'description' && !/[.?]$/.test(value)) return 'description must end a complete sentence'
  return undefined
}

/** Fail the build on an entry for a page the site does not render, or one that breaks a limit. */
export function checkPageMeta(renderedPaths) {
  for (const [repoPath, entry] of Object.entries(PAGE_META)) {
    if (!renderedPaths.has(repoPath)) {
      throw new Error(`page-meta.mjs describes ${repoPath}, which the site does not render: fix the path or remove the entry`)
    }
    for (const [field, value] of Object.entries(entry)) {
      const problem = fieldProblem(field, value)
      if (problem) throw new Error(`page-meta.mjs, ${repoPath}: ${problem}`)
    }
  }
}
